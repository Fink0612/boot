BEGIN
 INSERT INTO USUARIO_02(A02_NOME,A02_USUARIO,A02_SENHA,A02_EMAIL,A02_CODIGO_LINK,A02_STATUS)
 VALUES(p_nome,p_usuario,p_senha,p_email,p_link,p_status);
END$$
CREATE PROCEDURE IF NOT EXISTS PROC_INS_EMPRESA_USUARIO_PERFIL2(
 IN p_empresa BIGINT, IN p_usuario BIGINT, IN p_pvb INT, IN p_admin INT, IN p_chefe INT, IN p_padrao INT)
BEGIN
 INSERT INTO EMPRESA_USUARIO_PERFIL_03(A01_CODIGO,A02_CODIGO,A03_PERFIL_PARAVIVERBEM,
 A03_PERFIL_ADMINISTRADOR,A03_PERFIL_CHEFE,A03_PERFIL_PADRAO)
 VALUES(p_empresa,p_usuario,p_pvb,p_admin,p_chefe,p_padrao);
END$$
DELIMITER ;
